using System;
using System.Collections.Generic;
using System.Net;
using System.Net.Sockets;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;
using AutoCAD.Gateway.Contracts;
using AutoCAD.Gateway.Core;
using AutoCAD.Gateway.Services;

namespace AutoCAD.Gateway.Server;

/// <summary>
/// Loopback HTTP/1.1 server based on <see cref="TcpListener"/> exposing the AutoCAD Gateway API.
/// Enforces per-session token authentication, loopback Host binding, Origin/Referer rejection,
/// and bounded request reading before dispatching onto AutoCAD's main thread.
/// </summary>
public sealed class HttpGatewayServer
{
    private const int MaxConsecutiveAcceptFailures = 20;
    private const long MaxDrainBytes = 8L * GatewayProtocol.MaxBodyBytes;
    private static readonly TimeSpan HeadReadTimeout = TimeSpan.FromSeconds(10);
    private static readonly TimeSpan BodyReadTimeout = TimeSpan.FromSeconds(30);
    private static readonly TimeSpan DrainTimeout = TimeSpan.FromSeconds(5);

    private static readonly Lazy<HttpGatewayServer> LazyInstance = new(() => new HttpGatewayServer());

    /// <summary>Gets the shared singleton instance of the Gateway server.</summary>
    public static HttpGatewayServer Instance => LazyInstance.Value;

    private static readonly Lock TokenLock = new();
    private static string _activeToken =
        Environment.GetEnvironmentVariable("AUTOCAD_GATEWAY_TOKEN")?.Trim() ?? string.Empty;
    private static bool _tokenWasAutoGenerated;

    /// <summary>
    /// Gets or sets the active token required in the 'X-Gateway-Token' header.
    /// Initialized from AUTOCAD_GATEWAY_TOKEN or minted fresh as a 32-byte random hex secret on Start.
    /// </summary>
    public static string ActiveToken
    {
        get
        {
            lock (TokenLock)
            {
                return _activeToken;
            }
        }
        set
        {
            lock (TokenLock)
            {
                _activeToken = value ?? string.Empty;
                _tokenWasAutoGenerated = false;
            }
        }
    }

    private readonly Lock _sync = new();
    private readonly IAutoCADCommandDispatcher _dispatcher;
    private readonly IAutoCADContextReader _contextReader;
    private readonly RequestRouter _router;

    private TcpListener? _listener;
    private CancellationTokenSource? _cts;
    private int _boundPort;
    private string? _instanceFilePath;

    private HttpGatewayServer()
    {
        _dispatcher = new AutoCADCommandDispatcher();
        _contextReader = new AutoCADContextReader();
        _router = new RequestRouter(_dispatcher, _contextReader);
    }

    /// <summary>Gets a value indicating whether the server is listening for loopback connections.</summary>
    public bool IsRunning
    {
        get
        {
            lock (_sync)
            {
                return _listener is not null;
            }
        }
    }

    /// <summary>Gets the actual TCP port currently bound on 127.0.0.1 (0 when stopped).</summary>
    public int BoundPort
    {
        get
        {
            lock (_sync)
            {
                return _boundPort;
            }
        }
    }

    /// <summary>Gets the path of the active instance discovery JSON file, if published.</summary>
    public string? InstanceFilePath
    {
        get
        {
            lock (_sync)
            {
                return _instanceFilePath;
            }
        }
    }

    /// <summary>
    /// Starts the loopback TCP listener on <paramref name="port"/> (falling back to an ephemeral port if occupied),
    /// mints an ephemeral session token if none is configured, and publishes the instance file.
    /// </summary>
    public void Start(int port = GatewayProtocol.DefaultPort)
    {
        if (port is < 0 or > 65535)
        {
            port = GatewayProtocol.DefaultPort;
        }

        TcpListener listener;
        CancellationToken ct;

        lock (_sync)
        {
            if (_listener is not null)
            {
                return;
            }

            try
            {
                listener = new TcpListener(IPAddress.Loopback, port);
                listener.Start();
            }
            catch (SocketException) when (port != 0)
            {
                listener = new TcpListener(IPAddress.Loopback, 0);
                listener.Start();
            }

            string token;
            lock (TokenLock)
            {
                if (string.IsNullOrEmpty(_activeToken))
                {
                    _activeToken = Convert.ToHexString(RandomNumberGenerator.GetBytes(32));
                    _tokenWasAutoGenerated = true;
                }

                token = _activeToken;
            }

            _listener = listener;
            _boundPort = ((IPEndPoint)listener.LocalEndpoint).Port;
            _cts = new CancellationTokenSource();
            ct = _cts.Token;

            try
            {
                PublishCurrentInstanceLocked(token);
            }
            catch
            {
                StopLocked(_listener);
                throw;
            }
        }

        int sessionPort = BoundPort;
        _ = Task.Run(() => AcceptLoopAsync(listener, sessionPort, ct));
    }

    /// <summary>
    /// Starts the Gateway server by parsing the port from a URL prefix such as "http://127.0.0.1:5055/".
    /// </summary>
    public void Start(string urlPrefix)
    {
        int port = GatewayProtocol.TryNormalizeHttpUrl(urlPrefix, out Uri? uri) && uri is not null && uri.Port > 0
            ? uri.Port
            : GatewayProtocol.DefaultPort;
        Start(port);
    }

    /// <summary>Updates and persists the active session instance descriptor (e.g., after AI_SET_TOKEN).</summary>
    public void RefreshInstanceDescriptor()
    {
        lock (_sync)
        {
            if (_listener is null)
            {
                return;
            }

            string token;
            lock (TokenLock)
            {
                token = _activeToken;
            }

            PublishCurrentInstanceLocked(token);
        }
    }

    /// <summary>Stops the loopback listener, deletes the instance discovery file, and clears ephemeral tokens.</summary>
    public void Stop()
    {
        lock (_sync)
        {
            StopLocked(_listener);
        }
    }

    private void StopIfOwner(TcpListener owner)
    {
        lock (_sync)
        {
            if (ReferenceEquals(_listener, owner))
            {
                StopLocked(owner);
            }
        }
    }

    private void StopLocked(TcpListener? listener)
    {
        CancellationTokenSource? cts = _cts;
        _cts = null;
        _listener = null;
        _boundPort = 0;
        _instanceFilePath = null;

        try
        {
            cts?.Cancel();
            listener?.Stop();
        }
        catch
        {
            // Ignore shutdown races
        }
        finally
        {
            cts?.Dispose();
            InstanceDiscovery.Remove(Environment.ProcessId);
            lock (TokenLock)
            {
                if (_tokenWasAutoGenerated)
                {
                    _activeToken = string.Empty;
                    _tokenWasAutoGenerated = false;
                }
            }
        }
    }

    private void PublishCurrentInstanceLocked(string token)
    {
        var descriptor = new InstanceDescriptor
        {
            Pid = Environment.ProcessId,
            Port = _boundPort,
            Token = token,
            StartedUtc = DateTime.UtcNow.ToString("o"),
            Product = SafeProductName(),
        };

        _instanceFilePath = InstanceDiscovery.Publish(descriptor);
    }

    private static string? SafeProductName()
    {
        try
        {
            return Autodesk.AutoCAD.ApplicationServices.Core.Application.GetSystemVariable("PRODUCT") as string;
        }
        catch
        {
            return null;
        }
    }

    private async Task AcceptLoopAsync(TcpListener listener, int sessionPort, CancellationToken ct)
    {
        int failures = 0;

        while (!ct.IsCancellationRequested)
        {
            TcpClient client;
            try
            {
                client = await listener.AcceptTcpClientAsync(ct).ConfigureAwait(false);
                failures = 0;
            }
            catch (OperationCanceledException)
            {
                return;
            }
            catch (ObjectDisposedException)
            {
                return;
            }
            catch (SocketException)
            {
                if (ct.IsCancellationRequested)
                {
                    return;
                }

                if (++failures >= MaxConsecutiveAcceptFailures)
                {
                    StopIfOwner(listener);
                    return;
                }

                try
                {
                    await Task.Delay(50 * failures, ct).ConfigureAwait(false);
                }
                catch (OperationCanceledException)
                {
                    return;
                }

                continue;
            }

            _ = Task.Run(() => HandleClientAsync(client, sessionPort, ct));
        }
    }

    private async Task HandleClientAsync(TcpClient client, int sessionPort, CancellationToken ct)
    {
        using (client)
        {
            try
            {
                client.NoDelay = true;
                await using NetworkStream stream = client.GetStream();

                HttpHeadReadResult head;
                using (var headTimeout = CancellationTokenSource.CreateLinkedTokenSource(ct))
                {
                    headTimeout.CancelAfter(HeadReadTimeout);
                    head = await HttpWireCodec.ReadHeadAsync(stream, GatewayProtocol.MaxHeaderBytes, headTimeout.Token)
                        .ConfigureAwait(false);
                }

                if (head.Closed)
                {
                    return;
                }

                if (head.HeaderTooLarge)
                {
                    await SendRefusalAsync(
                        client.Client,
                        stream,
                        431,
                        "header_too_large",
                        "HTTP request header exceeds maximum allowed size.",
                        ct).ConfigureAwait(false);
                    return;
                }

                if (!HttpRequestGuard.TryParseHead(
                    head.HeaderText, out string method, out string rawTarget, out Dictionary<string, string> headers))
                {
                    await SendRefusalAsync(
                        client.Client,
                        stream,
                        400,
                        "bad_request",
                        "Malformed HTTP request head.",
                        ct).ConfigureAwait(false);
                    return;
                }

                string expectedToken = ActiveToken;
                Admission admission = HttpRequestGuard.Admit(
                    method, headers, expectedToken, sessionPort, GatewayProtocol.MaxBodyBytes);

                if (!admission.Admitted)
                {
                    byte[] refusal = JsonSerializer.SerializeToUtf8Bytes(admission.Refusal, GatewayProtocol.WireJsonOptions);
                    await HttpWireCodec.WriteResponseAsync(stream, admission.Status, refusal, ct).ConfigureAwait(false);
                    await HttpWireCodec.FinishRefusalAsync(client.Client, stream, MaxDrainBytes, DrainTimeout, ct)
                        .ConfigureAwait(false);
                    return;
                }

                if (!HttpRequestGuard.TrySplitTarget(rawTarget, out string path, out Dictionary<string, string> query))
                {
                    await SendRefusalAsync(
                        client.Client,
                        stream,
                        400,
                        "bad_request",
                        "Malformed request target.",
                        ct).ConfigureAwait(false);
                    return;
                }

                HttpBodyReadResult bodyResult;
                using (var bodyTimeout = CancellationTokenSource.CreateLinkedTokenSource(ct))
                {
                    bodyTimeout.CancelAfter(BodyReadTimeout);
                    bodyResult = await HttpWireCodec.ReadBodyAsync(
                        stream, admission.ContentLength, head.LeftoverBytes, bodyTimeout.Token)
                        .ConfigureAwait(false);
                }

                if (!bodyResult.IsComplete)
                {
                    await SendRefusalAsync(
                        client.Client,
                        stream,
                        400,
                        "bad_request",
                        "Incomplete HTTP request body.",
                        ct).ConfigureAwait(false);
                    return;
                }

                if (bodyResult.InvalidUtf8)
                {
                    await SendRefusalAsync(
                        client.Client,
                        stream,
                        400,
                        "bad_utf8",
                        "Request body must be valid UTF-8.",
                        ct).ConfigureAwait(false);
                    return;
                }

                var (statusCode, responseBody) = await _router.RouteRequestAsync(
                    method, path, query, bodyResult.Body, sessionPort).ConfigureAwait(false);
                await HttpWireCodec.WriteResponseAsync(stream, statusCode, Encoding.UTF8.GetBytes(responseBody), ct)
                    .ConfigureAwait(false);
            }
            catch (OperationCanceledException)
            {
                // Normal timeout or gateway shutdown
            }
            catch (IOException)
            {
                // Client disconnected early
            }
            catch (SocketException)
            {
                // Socket closed by peer
            }
            catch (Exception ex)
            {
                System.Diagnostics.Trace.TraceError("AutoCAD Gateway socket error: {0}", ex);
            }
        }
    }

    private static async Task SendRefusalAsync(
        Socket socket,
        NetworkStream stream,
        int status,
        string code,
        string message,
        CancellationToken ct)
    {
        byte[] refusal = JsonSerializer.SerializeToUtf8Bytes(ToolEnvelope.Failure(code, message), GatewayProtocol.WireJsonOptions);
        await HttpWireCodec.WriteResponseAsync(stream, status, refusal, ct).ConfigureAwait(false);
        await HttpWireCodec.FinishRefusalAsync(socket, stream, MaxDrainBytes, DrainTimeout, ct).ConfigureAwait(false);
    }
}
